export function translateText(text: string, language: AppLanguage): string {
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const key = text.trim();
  if (language === "vi") {
    if (Object.prototype.hasOwnProperty.call(englishTranslations, key)) {
      return text;
    }
    const source = Object.entries(englishTranslations).find(
      ([, target]) => target === key
    )?.[0];
    return source ? `${leading}${source}${trailing}` : text;
  }
  if (englishTranslations[key]) {
    return `${leading}${englishTranslations[key]}${trailing}`;
  }
  const translated = sortedTranslations
    .reduce((value, [source, target]) => value.split(source).join(target), key);
  return `${leading}${translated}${trailing}`;
}

const sortedTranslations = Object.entries(englishTranslations)
  .filter(([source]) => source.length > 3)
  .sort(([left], [right]) => right.length - left.length);
